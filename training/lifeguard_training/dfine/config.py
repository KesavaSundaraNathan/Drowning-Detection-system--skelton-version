"""
D-FINE YAML for the client dataset. It `__include__`s the repo's own
`configs/dfine/custom/dfine_hgnetv2_<size>_custom.yml` (absolute path — the
YAMLConfig loader joins include paths onto the config's folder, and joining an
absolute path yields that path) and overrides only what this project needs.

Choices (documented so the eval harness can A/B them):
  * input size 960 by default — 15–30 people in a pool camera are small; the
    exported ONNX is static at this size (rtm_backend reads it from the model).
  * HGNetv2 `pretrained: False` — the backbone weights come from the COCO-only
    D-FINE checkpoint passed with `-t`, so nothing else is downloaded.
"""

from __future__ import annotations

from pathlib import Path

from lifeguard_training.dfine import CLASSES

SIZES = ("n", "s", "m", "l", "x")


def base_config(repo: Path, size: str) -> Path:
    if size not in SIZES:
        raise ValueError(f"size must be one of {SIZES}")
    p = Path(repo) / "configs" / "dfine" / "custom" / f"dfine_hgnetv2_{size}_custom.yml"
    return p


def _q(p: Path) -> str:
    return Path(p).resolve().as_posix()


def write_config(
    repo: Path,
    size: str,
    images: Path,
    annotations: Path,
    out_dir: Path,
    imgsz: int = 960,
    epochs: int = 80,
    batch: int = 8,
    workers: int = 4,
    check_repo: bool = True,
    path: Path | None = None,
) -> Path:
    base = base_config(repo, size)
    if check_repo and not base.exists():
        raise FileNotFoundError(f"{base} not found — is --dfine-repo a checkout of github.com/Peterande/D-FINE?")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = Path(path) if path else out_dir / f"lifeguard_dfine_{size}.yml"
    images, annotations = Path(images), Path(annotations)
    # The base m/s configs set stop_epoch (mosaic-off point) and the augmentation
    # policy switch to 120, both far above any short/smoke run's epoch count, so
    # det_solver.py's "best_stg1/2.pth" save path (only reachable once
    # epoch >= stop_epoch) never fires and every run silently falls back to
    # last.pth (train_detector_dfine.py already handles that fallback). Scaling
    # both to just under the requested epoch count lets a short run still reach
    # and exercise that code path instead of only ever producing last.pth.
    stop_epoch = max(1, epochs - 1)
    yml = f"""# generated by training/dfine/config.py — Life Guard zone-aware detector
__include__: ['{_q(base)}']

output_dir: {_q(out_dir / "run")}
num_classes: {len(CLASSES)}            # {", ".join(f"{i} {n}" for i, n in enumerate(CLASSES))}
remap_mscoco_category: False
eval_spatial_size: [{imgsz}, {imgsz}]
# The real key D-FINE's training loop reads is "epochs" (src/solver/det_solver.py:
# `for epoch in range(start_epoch, args.epochs)`), NOT "epoches" — an earlier
# version of this file used the misspelling, which D-FINE silently ignored as an
# unknown key, so every run trained for the base config's full schedule (132
# epochs for m/s, ~3h/epoch on a laptop GPU) regardless of --epochs. Verified by
# grepping the cloned repo for "epoches" (zero matches) vs "epochs" (the real key).
epochs: {epochs}

HGNetv2:
  pretrained: False             # backbone comes from the COCO-only checkpoint (-t)

train_dataloader:
  total_batch_size: {batch}
  num_workers: {workers}
  dataset:
    img_folder: {_q(images / "train")}
    ann_file: {_q(annotations / "instances_train.json")}
    transforms:
      policy:
        epoch: {stop_epoch}
  collate_fn:
    base_size: {imgsz}
    stop_epoch: {stop_epoch}

val_dataloader:
  total_batch_size: {batch}
  num_workers: {workers}
  dataset:
    img_folder: {_q(images / "val")}
    ann_file: {_q(annotations / "instances_val.json")}
"""
    path.write_text(yml, encoding="utf-8")
    return path
